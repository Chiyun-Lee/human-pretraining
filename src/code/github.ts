// Reading a public GitHub repository: which files it has, which are worth
// showing, and how they nest. The parsing and filtering are pure and unit-tested.

export interface RepoRef {
  owner: string
  repo: string
  branch?: string
}

export interface ListedFile {
  path: string
  size: number
}

/** A GitHub repository address, or null if the text is something else (a DOI, a paper URL). */
export function parseRepo(input: string): RepoRef | null {
  const match = input.trim().match(/^(?:https?:\/\/)?(?:www\.)?github\.com\/([\w.-]+)\/([\w.-]+?)(?:\.git)?(?:\/tree\/([^?#]+?))?\/?(?:[?#].*)?$/i)
  return match ? { owner: match[1]!, repo: match[2]!, ...(match[3] && { branch: match[3] }) } : null
}

// Folders that are never the project's own code.
const IGNORED = /(^|\/)(node_modules|\.git|dist|build|out|target|vendor|\.next|\.venv|venv|__pycache__|\.idea|\.vscode|coverage)\//
const BINARY = /\.(png|jpe?g|gif|webp|ico|bmp|tiff?|pdf|zip|gz|tar|tgz|7z|woff2?|ttf|otf|eot|mp[34]|mov|wav|ogg|bin|exe|dll|so|dylib|class|jar|wasm|pyc|onnx|pt|ckpt|npy|npz|parquet|sqlite|db)$/i
const LOCK = /(^|\/)(package-lock\.json|yarn\.lock|pnpm-lock\.yaml|bun\.lockb?|Cargo\.lock|poetry\.lock|uv\.lock|Gemfile\.lock|composer\.lock|go\.sum|Pipfile\.lock)$/
const MAX_READABLE = 100_000

export const isListed = (path: string) => !IGNORED.test(path + '/') && !IGNORED.test(path)

const kilobytes = (size: number) => (size >= 1_000_000 ? `${(size / 1_000_000).toFixed(1)} MB` : `${Math.round(size / 1000)} KB`)

/** Why a file is shown as a placeholder instead of being opened, or null if it can be read. */
export function placeholder(file: ListedFile): string | null {
  if (BINARY.test(file.path)) return `Binary file · ${kilobytes(file.size)}`
  if (LOCK.test(file.path)) return 'Lock file, generated by the package manager'
  if (/\.min\.(js|css)$|\.map$/.test(file.path)) return 'Generated file'
  if (/\.svg$/i.test(file.path)) return 'Image'
  if (file.size > MAX_READABLE) return `Large file · ${kilobytes(file.size)}`
  if (file.size === 0) return 'Empty file'
  return null
}

/** The documentation and manifest files that say most about a project, most telling first. */
export function docsToRead(files: ListedFile[]): string[] {
  const rank = (path: string): number => {
    const depth = path.split('/').length - 1
    const name = path.split('/').pop()!.toLowerCase()
    if (depth > 1) return 0
    if (/^readme(\.|$)/.test(name)) return depth === 0 ? 10 : 4
    if (/^(claude|agents|architecture|design|contributing)\.md$/.test(name)) return depth === 0 ? 8 : 3
    if (/^(package\.json|pyproject\.toml|cargo\.toml|go\.mod|requirements\.txt|gemfile|pom\.xml|build\.gradle|composer\.json|deno\.json|makefile|dockerfile|docker-compose\.ya?ml)$/.test(name)) return depth === 0 ? 7 : 5
    return 0
  }
  return files
    .filter((file) => rank(file.path) > 0 && placeholder(file) === null)
    .sort((a, b) => rank(b.path) - rank(a.path) || a.path.length - b.path.length)
    .slice(0, 8)
    .map((file) => file.path)
}

export interface TreeNode {
  /** The label: one name, or several joined with "/" when a folder holds nothing but another folder. */
  name: string
  path: string
  /** Present for a file. */
  file?: ListedFile
  children: TreeNode[]
}

/** Nests the files into folders (folders first, then files, each alphabetical). */
export function buildTree(files: ListedFile[]): TreeNode[] {
  const root: TreeNode = { name: '', path: '', children: [] }
  for (const file of files) {
    let node = root
    const parts = file.path.split('/')
    parts.forEach((part, i) => {
      const path = parts.slice(0, i + 1).join('/')
      let child = node.children.find((c) => c.path === path)
      if (!child) {
        child = { name: part, path, children: [], ...(i === parts.length - 1 && { file }) }
        node.children.push(child)
      }
      node = child
    })
  }
  const tidy = (node: TreeNode): TreeNode => {
    let current = node
    // A folder whose only content is another folder is shown as one row.
    while (!current.file && current.children.length === 1 && !current.children[0]!.file && current !== root) {
      const only = current.children[0]!
      current = { ...only, name: `${current.name}/${only.name}` }
    }
    const children = current.children.map(tidy).sort((a, b) => Number(!!a.file) - Number(!!b.file) || a.name.localeCompare(b.name))
    return { ...current, children }
  }
  return tidy(root).children
}

const API = 'https://api.github.com'

async function github<T>(path: string, accept = 'application/vnd.github+json'): Promise<T> {
  const response = await fetch(API + path, { headers: { Accept: accept } })
  if (response.status === 404) throw new Error('That repository was not found. Only public GitHub repositories can be added.')
  if (response.status === 403 || response.status === 429) throw new Error('GitHub is limiting requests from your network. Try again in a few minutes.')
  if (!response.ok) throw new Error('GitHub could not be reached. Try again.')
  return (accept.endsWith('sha') ? response.text() : response.json()) as Promise<T>
}

/** The files of a repository at the newest commit of a branch (its default branch unless one is given). */
export async function readRepository(ref: RepoRef): Promise<{ owner: string; repo: string; commit: string; files: ListedFile[] }> {
  const about = await github<{ default_branch: string; name: string; owner: { login: string } }>(`/repos/${ref.owner}/${ref.repo}`)
  const branch = ref.branch ?? about.default_branch
  const commit = (await github<string>(`/repos/${ref.owner}/${ref.repo}/commits/${encodeURIComponent(branch)}`, 'application/vnd.github.sha')).trim()
  const tree = await github<{ tree: { path: string; type: string; size?: number }[] }>(`/repos/${ref.owner}/${ref.repo}/git/trees/${commit}?recursive=1`)
  const files = tree.tree
    .filter((entry) => entry.type === 'blob' && isListed(entry.path))
    .map((entry) => ({ path: entry.path, size: entry.size ?? 0 }))
    .slice(0, 3000)
  if (files.length === 0) throw new Error('That repository has no files to show.')
  return { owner: about.owner.login, repo: about.name, commit, files }
}

/** A file's text at a commit. */
export async function readFile(owner: string, repo: string, commit: string, path: string): Promise<string> {
  const url = `https://raw.githubusercontent.com/${owner}/${repo}/${commit}/${path.split('/').map(encodeURIComponent).join('/')}`
  const response = await fetch(url)
  if (!response.ok) throw new Error('That file could not be read from GitHub.')
  return response.text()
}
